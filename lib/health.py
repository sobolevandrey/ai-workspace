def fmt(ts):
    return datetime.fromtimestamp(ts).strftime("%Y-%m-%d %H:%M")


def project_dirs(ws, chron=""):
    pr = ws / "projects"
    res = []
    if not pr.exists():
        return res
    for p in sorted(pr.iterdir()):
        if not p.is_dir() or p.name.startswith(("_", ".")):
            continue
        if (p / ".aiw-group").exists():
            res += [c for c in sorted(p.iterdir()) if c.is_dir() and not c.name.startswith(("_", ".")) and c.name != chron]
        else:
            res.append(p)
    return res


def activity(p, chron, status, children=()):
    """Самый свежий рабочий файл проекта (без служебных, летописи и статуса)."""
    newest, files = 0.0, []
    skip_sub = {chron} | set(children)
    for root, dirs, fs in os.walk(p):
        rel_root = Path(root).relative_to(p)
        dirs[:] = [d for d in dirs if d not in SKIP_DIRS and not d.startswith(".")
                   and not (rel_root == Path(".") and d in skip_sub)]
        for f in fs:
            if f in SKIP_FILES or f == status or os.path.splitext(f)[1] in SKIP_EXT or f.startswith("."):
                continue
            fp = Path(root) / f
            try:
                m = fp.lstat().st_mtime
            except OSError:
                continue
            files.append((m, fp))
            newest = max(newest, m)
    return newest, files


def check_project(p, names, lang, now, children=()):
    T = TXT[lang]
    chron, status = names["chronicle"], names["status"]
    summary_name = "ИТОГИ.md" if lang == "ru" else "SUMMARY.md"
    st = p / status
    cdir = p / chron
    months = sorted(cdir.glob("[0-9][0-9][0-9][0-9]-[0-9][0-9].md")) if cdir.exists() else []
    log_m = max((m.stat().st_mtime for m in months), default=0)
    st_m = st.stat().st_mtime if st.exists() else 0
    last_rec = max(log_m, st_m)
    newest, files = activity(p, chron, status, children)
    issues = []

    unlogged = sorted([(m, f) for m, f in files if m > last_rec + 60], reverse=True)
    if unlogged and last_rec:                      # нет ни одной записи — проект ещё не «в системе»
        sample = ", ".join(f"`{f.relative_to(p).as_posix()}`" for _, f in unlogged[:5])
        issues.append(T["unlogged"].format(n=len(unlogged), last=fmt(unlogged[0][0]), files=sample))
    elif unlogged and not last_rec and newest > now - 30 * 86400:
        sample = ", ".join(f"`{f.relative_to(p).as_posix()}`" for _, f in unlogged[:5])
        issues.append(T["unlogged"].format(n=len(unlogged), last=fmt(unlogged[0][0]), files=sample))

    if log_m and st_m and log_m > st_m + 3600:
        issues.append(T["stale"].format(log=fmt(log_m), st=fmt(st_m)))

    cur = datetime.fromtimestamp(now).strftime("%Y-%m")
    summ = cdir / summary_name
    stext = summ.read_text(encoding="utf-8") if summ.exists() else ""
    missing = [m.stem for m in months if m.stem < cur and f"## {m.stem}" not in stext
               and re.search(r"(?m)^### ", m.read_text(encoding="utf-8"))]
    if missing:
        issues.append(T["nosum"].format(months=", ".join(missing), chron=chron))

    big = []
    for f, lim, label in ((st, LIMITS["status"], status), (p / "AGENTS.md", LIMITS["agents"], "AGENTS.md")):
        if f.exists():
            n = len(f.read_text(encoding="utf-8").splitlines())
            if n > lim:
                big.append(f"{label} {n}/{lim}")
    for m in months:
        n = len(m.read_text(encoding="utf-8").splitlines())
        if n > LIMITS["month"]:
            big.append(f"{chron}/{m.name} {n}/{LIMITS['month']}")
    if big:
        issues.append(T["big"].format(what=", ".join(big)))
    return issues, max(newest, last_rec), st


def write_block(st: Path, issues, lang, now):
    """Вставить/убрать блок в СТАТУС.md, сохранив время изменения файла."""
    if not st.exists():
        if not issues:
            return
        st.write_text(f"# {st.stem}\n", encoding="utf-8")
        os.utime(st, (0, 0))
    text = st.read_text(encoding="utf-8")
    stat = st.stat()
    clean = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END) + r"\n*", "", text, flags=re.S)
    if issues:
        T = TXT[lang]
        block = "\n".join([BEGIN, T["head"].format(d=fmt(now)), *issues, T["hint"], END, ""]) + "\n"
        lines = clean.splitlines(keepends=True)
        i = 1 if lines and lines[0].startswith("# ") else 0
        while i < len(lines) and (lines[i].startswith(">") or not lines[i].strip()):
            i += 1
        new = "".join(lines[:i]) + block + "".join(lines[i:])
    else:
        new = clean
    if new != text:
        st.write_text(new, encoding="utf-8")
        os.utime(st, (stat.st_atime, stat.st_mtime))      # не маскировать долг


def first_line(st: Path):
    if not st.exists():
        return "—"
    t = re.sub(re.escape(BEGIN) + r".*?" + re.escape(END), "", st.read_text(encoding="utf-8"), flags=re.S)
    for l in t.splitlines():
        l = l.strip()
        if l.startswith(("- ", "* ", "1.")):
            return re.sub(r"[|`*]", "", l.lstrip("-*1. "))[:90]
    return "—"


def run(ws: Path, names: dict, lang="ru", index_name=None, verbose=True, dry=False):
    lang = lang if lang in TXT else "en"
    T = TXT[lang]
    now = time.time()
    rows, with_issues, stale = [], 0, []
    for p in project_dirs(ws, names["chronicle"]):
        issues, last, st = check_project(p, names, lang, now)
        if dry:
            for i in issues:
                print(f"    [{p.name}] {i[:230]}")
        elif st.exists() or issues:
            write_block(st, issues, lang, now)
        rel = p.relative_to(ws / "projects").as_posix()
        if issues:
            with_issues += 1
            if verbose:
                print(f"  ⚠ {rel}: {len(issues)}")
        if last and now - last > STALE_DAYS * 86400:
            stale.append(rel)
        rows.append((last, rel, first_line(st), "⚠ " + str(len(issues)) if issues else "✓"))

    # индекс проектов
    rows.sort(reverse=True)
    idx = [T["idx_title"], "", T["idx_note"].format(d=fmt(now)), "", T["idx_head"], "|---|---|---|---|"]
    idx += [f"| {r} | {fmt(l)[:10] if l else '—'} | {s} | {a} |" for l, r, s, a in rows]
    if stale:
        idx.append(T["archive"].format(n=STALE_DAYS, list=", ".join(stale)))
    if not dry:
        (ws / (index_name or ("ПРОЕКТЫ.md" if lang == "ru" else "PROJECTS.md"))).write_text("\n".join(idx) + "\n", encoding="utf-8")
    else:
        print("\n".join(idx))

    # общие проверки
    warn = []
    ctx = sum(len(f.read_text(encoding="utf-8")) for f in (ws / "rules/core.md", ws / "memory/profile.md") if f.exists())
    if ctx > CONTEXT_BUDGET:
        warn.append(T["ctx"].format(n=ctx, b=CONTEXT_BUDGET))
    sk = [d for d in (ws / "skills").iterdir() if (d / "SKILL.md").exists()] if (ws / "skills").exists() else []
    if len(sk) > SKILLS_WARN:
        warn.append(T["skills"].format(n=len(sk), w=SKILLS_WARN))
    inbox = ws / "memory/inbox.md"
    if inbox.exists():
        body = inbox.read_text(encoding="utf-8").split("---", 1)[-1].strip()
        if body:
            warn.append(T["inbox"].format(n=len(body.splitlines())))
    if verbose:
        for w in warn:
            print("  " + w)
        print("  " + T["summary"].format(p=len(rows), d=with_issues))
    return rows, warn
